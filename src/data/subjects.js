export function getNewSubjectsForGrade(grade) {
  return NEW_SUBJECTS_BY_GRADE[grade] ?? []
}

export function getSubjectsForGrade(grade) {
  return SUBJECTS_BY_GRADE[grade] ?? SUBJECTS_BY_GRADE[11] ?? []
}

/** Новые предметы — в начале расписания для знакомства */
export function getSubjectsForGradeIntroOrder(grade) {
  const all = getSubjectsForGrade(grade)
  const fresh = getNewSubjectsForGrade(grade)
  if (!fresh.length) return all
  return [...fresh, ...all.filter((s) => !fresh.includes(s))]
}

export function getNewSubjectDescription(subject) {
  return NEW_SUBJECT_DESCRIPTIONS[subject] ?? NEW_SUBJECT_SCHEDULE_LINE
}
